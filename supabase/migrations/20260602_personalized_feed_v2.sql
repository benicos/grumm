create or replace function public.get_personalized_feed(
  p_user_id uuid default null,
  p_limit integer default 20,
  p_session_id uuid default null,
  p_debug boolean default false,
  p_theme_slug text default null
)
returns table (
  id uuid,
  slug text,
  title text,
  hook text,
  content text,
  source text,
  source_url text,
  difficulty_level text,
  long_content text,
  seo_title text,
  seo_description text,
  event_day integer,
  event_month integer,
  event_year integer,
  published_at timestamptz,
  updated_at timestamptz,
  tone text,
  accent_color text,
  category_id uuid,
  category_name text,
  category_slug text,
  category_tone text,
  category_accent_color text,
  seen_by_user boolean,
  recommendation_score numeric,
  score_debug jsonb
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_is_admin boolean := coalesce(public.is_admin(), false);
  v_user_id uuid := null;
  v_limit integer := greatest(1, least(coalesce(p_limit, 20), 50));
  v_pool_limit integer := greatest(200, least(500, v_limit * 18));
  v_debug boolean := coalesce(p_debug, false) and v_is_admin;
  v_learning_goal text := 'strengthen';
begin
  if v_is_admin and p_user_id is not null then
    v_user_id := p_user_id;
  elsif v_auth_user_id is not null then
    v_user_id := v_auth_user_id;
  else
    v_user_id := null;
  end if;

  select coalesce(profiles.learning_goal, 'strengthen')
  into v_learning_goal
  from public.profiles
  where profiles.id = v_user_id;

  v_learning_goal := coalesce(v_learning_goal, 'strengthen');

  if v_learning_goal not in ('basics', 'strengthen', 'advanced') then
    v_learning_goal := 'strengthen';
  end if;

  if p_session_id is not null then
    insert into public.feed_sessions (id, user_id, last_seen_at)
    values (p_session_id, v_user_id, now())
    on conflict on constraint feed_sessions_pkey do update set
      user_id = coalesce(excluded.user_id, public.feed_sessions.user_id),
      last_seen_at = now();
  end if;

  return query
  with theme_affinity as (
    select
      source.category_id,
      count(*)::numeric as affinity_count
    from (
      select facts.category_id
      from public.likes
      join public.facts on facts.id = likes.fact_id
      where likes.user_id = v_user_id
      union all
      select facts.category_id
      from public.saves
      join public.facts on facts.id = saves.fact_id
      where saves.user_id = v_user_id
      union all
      select facts.category_id
      from public.user_fact_views
      join public.facts on facts.id = user_fact_views.fact_id
      where user_fact_views.user_id = v_user_id
        and user_fact_views.first_viewed_at >= now() - interval '45 days'
    ) source
    group by source.category_id
  ),
  candidate_pool as (
    (
    select facts.id
    from public.facts
    join public.categories on categories.id = facts.category_id
    where facts.status = 'published'
      and (p_theme_slug is null or categories.slug = p_theme_slug)
      and not exists (
        select 1
        from public.user_fact_views
        where user_fact_views.user_id = v_user_id
          and user_fact_views.fact_id = facts.id
    )
    order by facts.published_at desc nulls last, facts.updated_at desc
    limit v_pool_limit / 2
    )

    union

    (
    select facts.id
    from public.facts
    join public.categories on categories.id = facts.category_id
    where facts.status = 'published'
      and (p_theme_slug is null or categories.slug = p_theme_slug)
      and facts.published_at >= now() - interval '90 days'
    order by facts.published_at desc nulls last, facts.updated_at desc
    limit v_pool_limit / 4
    )

    union

    (
    select facts.id
    from public.facts
    join public.categories on categories.id = facts.category_id
    join theme_affinity on theme_affinity.category_id = facts.category_id
    where facts.status = 'published'
      and (p_theme_slug is null or categories.slug = p_theme_slug)
    order by theme_affinity.affinity_count desc, facts.published_at desc nulls last
    limit v_pool_limit / 4
    )

    union

    (
    select facts.id
    from public.facts
    join public.categories on categories.id = facts.category_id
    where facts.status = 'published'
      and (p_theme_slug is null or categories.slug = p_theme_slug)
      and facts.event_month = extract(month from current_date)::integer
      and facts.event_day between greatest(1, extract(day from current_date)::integer - 2)
        and least(31, extract(day from current_date)::integer + 2)
    order by abs(facts.event_day - extract(day from current_date)::integer), facts.published_at desc nulls last
    limit 60
    )

    union

    (
    select facts.id
    from public.facts
    join public.categories on categories.id = facts.category_id
    where facts.status = 'published'
      and (p_theme_slug is null or categories.slug = p_theme_slug)
    order by random()
    limit greatest(40, v_limit * 3)
    )
  ),
  hydrated as (
    select
      facts.*,
      categories.name as category_name,
      categories.slug as category_slug,
      categories.tone as category_tone,
      categories.accent_color as category_accent_color,
      user_fact_views.first_viewed_at,
      feed_session_items.served_at,
      coalesce(theme_affinity.affinity_count, 0) as affinity_count,
      coalesce(fact_engagement_stats.views_count, 0) as views_count,
      coalesce(fact_engagement_stats.unique_viewers_count, 0) as unique_viewers_count,
      coalesce(fact_engagement_stats.likes_count, 0) as likes_count,
      coalesce(fact_engagement_stats.saves_count, 0) as saves_count,
      coalesce(fact_engagement_stats.shares_count, 0) as shares_count
    from candidate_pool
    join public.facts on facts.id = candidate_pool.id
    join public.categories on categories.id = facts.category_id
    left join public.user_fact_views
      on user_fact_views.fact_id = facts.id
      and user_fact_views.user_id = v_user_id
    left join public.feed_session_items
      on feed_session_items.fact_id = facts.id
      and feed_session_items.session_id = p_session_id
    left join theme_affinity on theme_affinity.category_id = facts.category_id
    left join public.fact_engagement_stats on fact_engagement_stats.fact_id = facts.id
  ),
  scored as (
    select
      hydrated.*,
      100::numeric as base_score,
      case
        when hydrated.first_viewed_at is null then 45
        when hydrated.first_viewed_at >= now() - interval '1 day' then -90
        when hydrated.first_viewed_at >= now() - interval '7 days' then -55
        when hydrated.first_viewed_at >= now() - interval '30 days' then -25
        else -8
      end::numeric as seen_penalty,
      case
        when hydrated.served_at is null then 0
        when hydrated.served_at >= now() - interval '30 minutes' then -80
        when hydrated.served_at >= now() - interval '6 hours' then -40
        else -15
      end::numeric as session_penalty,
      least(35, hydrated.affinity_count * 6)::numeric as theme_affinity_bonus,
      case
        when v_learning_goal = 'basics' and hydrated.difficulty_level = 'basic' then 25
        when v_learning_goal = 'basics' and hydrated.difficulty_level = 'intermediate' then 8
        when v_learning_goal = 'basics' then -15
        when v_learning_goal = 'advanced' and hydrated.difficulty_level = 'advanced' then 25
        when v_learning_goal = 'advanced' and hydrated.difficulty_level = 'intermediate' then 10
        when v_learning_goal = 'advanced' then -12
        when hydrated.difficulty_level = 'intermediate' then 25
        else 8
      end::numeric as level_match_bonus,
      case
        when hydrated.published_at >= now() - interval '7 days' then 14
        when hydrated.published_at >= now() - interval '30 days' then 8
        when hydrated.published_at >= now() - interval '90 days' then 3
        else 0
      end::numeric as freshness_bonus,
      case
        when hydrated.event_month = extract(month from current_date)::integer
          and hydrated.event_day = extract(day from current_date)::integer then 30
        when hydrated.event_month = extract(month from current_date)::integer
          and abs(hydrated.event_day - extract(day from current_date)::integer) <= 2 then 12
        else 0
      end::numeric as date_relevance_bonus,
      least(
        18,
        ln(1 + hydrated.views_count + hydrated.unique_viewers_count * 2 + hydrated.likes_count * 4 + hydrated.saves_count * 5 + hydrated.shares_count * 3) * 3
      )::numeric as engagement_bonus,
      (random() * 8)::numeric as random_bonus
    from hydrated
  ),
  ranked as (
    select
      scored.*,
      (
        scored.base_score +
        scored.seen_penalty +
        scored.session_penalty +
        scored.theme_affinity_bonus +
        scored.level_match_bonus +
        scored.freshness_bonus +
        scored.date_relevance_bonus +
        scored.engagement_bonus +
        scored.random_bonus
      )::numeric as final_score
    from scored
    order by final_score desc
    limit v_limit
  ),
  remembered as (
    insert into public.feed_session_items (session_id, fact_id, served_at)
    select p_session_id, ranked.id, now()
    from ranked
    where p_session_id is not null
    on conflict (session_id, fact_id) do update set served_at = excluded.served_at
    returning fact_id
  )
  select
    ranked.id,
    ranked.slug,
    ranked.title,
    ranked.hook,
    ranked.content,
    ranked.source,
    ranked.source_url,
    ranked.difficulty_level,
    ranked.long_content,
    ranked.seo_title,
    ranked.seo_description,
    ranked.event_day,
    ranked.event_month,
    ranked.event_year,
    ranked.published_at,
    ranked.updated_at,
    ranked.tone,
    ranked.accent_color,
    ranked.category_id,
    ranked.category_name,
    ranked.category_slug,
    ranked.category_tone,
    ranked.category_accent_color,
    ranked.first_viewed_at is not null as seen_by_user,
    round(ranked.final_score, 2) as recommendation_score,
    case
      when v_debug then jsonb_build_object(
        'base_score', ranked.base_score,
        'seen_penalty', ranked.seen_penalty,
        'session_penalty', ranked.session_penalty,
        'theme_affinity_bonus', ranked.theme_affinity_bonus,
        'level_match_bonus', ranked.level_match_bonus,
        'freshness_bonus', ranked.freshness_bonus,
        'date_relevance_bonus', ranked.date_relevance_bonus,
        'engagement_bonus', ranked.engagement_bonus,
        'random_bonus', round(ranked.random_bonus, 2),
        'final_score', round(ranked.final_score, 2)
      )
      else null
    end as score_debug
  from ranked;
end;
$$;

