insert into public.fact_engagement_stats (
  fact_id,
  views_count,
  unique_viewers_count,
  likes_count,
  saves_count,
  shares_count,
  updated_at
)
select
  facts.id,
  coalesce(read_events.views_count, 0),
  coalesce(unique_views.unique_viewers_count, 0),
  coalesce(likes.likes_count, 0),
  coalesce(saves.saves_count, 0),
  coalesce(shares.shares_count, 0),
  now()
from public.facts
left join (
  select fact_id, count(*)::integer as views_count
  from public.fact_read_events
  group by fact_id
) read_events on read_events.fact_id = facts.id
left join (
  select fact_id, count(*)::integer as unique_viewers_count
  from public.user_fact_views
  group by fact_id
) unique_views on unique_views.fact_id = facts.id
left join (
  select fact_id, count(*)::integer as likes_count
  from public.likes
  group by fact_id
) likes on likes.fact_id = facts.id
left join (
  select fact_id, count(*)::integer as saves_count
  from public.saves
  group by fact_id
) saves on saves.fact_id = facts.id
left join (
  select entity_id as fact_id, count(*)::integer as shares_count
  from public.analytics_events
  where entity_type = 'fact'
    and event_name in ('fact_shared', 'fact_share')
    and entity_id is not null
  group by entity_id
) shares on shares.fact_id = facts.id
on conflict (fact_id) do update set
  views_count = excluded.views_count,
  unique_viewers_count = excluded.unique_viewers_count,
  likes_count = excluded.likes_count,
  saves_count = excluded.saves_count,
  shares_count = excluded.shares_count,
  updated_at = now();

create or replace function public.bump_fact_engagement_stat(
  p_fact_id uuid,
  p_metric text,
  p_delta integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.fact_engagement_stats (fact_id)
  values (p_fact_id)
  on conflict (fact_id) do nothing;

  update public.fact_engagement_stats
  set
    views_count = greatest(
      0,
      views_count + case when p_metric = 'views_count' then p_delta else 0 end
    ),
    unique_viewers_count = greatest(
      0,
      unique_viewers_count + case when p_metric = 'unique_viewers_count' then p_delta else 0 end
    ),
    likes_count = greatest(
      0,
      likes_count + case when p_metric = 'likes_count' then p_delta else 0 end
    ),
    saves_count = greatest(
      0,
      saves_count + case when p_metric = 'saves_count' then p_delta else 0 end
    ),
    shares_count = greatest(
      0,
      shares_count + case when p_metric = 'shares_count' then p_delta else 0 end
    ),
    quiz_success_count = greatest(
      0,
      quiz_success_count + case when p_metric = 'quiz_success_count' then p_delta else 0 end
    ),
    quiz_attempt_count = greatest(
      0,
      quiz_attempt_count + case when p_metric = 'quiz_attempt_count' then p_delta else 0 end
    ),
    updated_at = now()
  where fact_id = p_fact_id;
end;
$$;

create or replace function public.track_fact_read_engagement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.bump_fact_engagement_stat(new.fact_id, 'views_count', 1);
  return new;
end;
$$;

