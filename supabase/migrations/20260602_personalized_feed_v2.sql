-- Grumm feed V2: lightweight server-side scoring with session memory.
-- The RPC limits candidates before scoring, so the feed request does not rank
-- the whole facts table as content volume grows.

create table if not exists public.analytics_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  anonymous_id text,
  platform text not null check (platform in ('web', 'ios')),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  facts_viewed integer not null default 0 check (facts_viewed >= 0),
  created_at timestamptz not null default now(),
  constraint analytics_sessions_identity_check check (
    user_id is not null or anonymous_id is not null
  )
);

create table if not exists public.analytics_events (
  id uuid primary key default gen_random_uuid(),
  session_id uuid references public.analytics_sessions(id) on delete set null,
  user_id uuid references auth.users(id) on delete set null,
  anonymous_id text,
  event_name text not null,
  entity_type text,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  platform text not null check (platform in ('web', 'ios')),
  created_at timestamptz not null default now(),
  constraint analytics_events_identity_check check (
    user_id is not null or anonymous_id is not null
  )
);

create table if not exists public.fact_read_events (
  id uuid primary key default gen_random_uuid(),
  session_id uuid references public.analytics_sessions(id) on delete set null,
  user_id uuid references auth.users(id) on delete set null,
  anonymous_id text,
  fact_id uuid not null references public.facts(id) on delete cascade,
  platform text not null check (platform in ('web', 'ios')),
  started_at timestamptz not null,
  ended_at timestamptz,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  completed boolean not null default false,
  created_at timestamptz not null default now(),
  constraint fact_read_events_identity_check check (
    user_id is not null or anonymous_id is not null
  )
);

create table if not exists public.fact_engagement_stats (
  fact_id uuid primary key references public.facts(id) on delete cascade,
  views_count integer not null default 0 check (views_count >= 0),
  unique_viewers_count integer not null default 0 check (unique_viewers_count >= 0),
  likes_count integer not null default 0 check (likes_count >= 0),
  saves_count integer not null default 0 check (saves_count >= 0),
  shares_count integer not null default 0 check (shares_count >= 0),
  quiz_success_count integer not null default 0 check (quiz_success_count >= 0),
  quiz_attempt_count integer not null default 0 check (quiz_attempt_count >= 0),
  updated_at timestamptz not null default now()
);

comment on table public.fact_engagement_stats is
  'Aggregated per-fact counters used by get_personalized_feed. Kept outside the feed request to avoid expensive runtime counts.';

